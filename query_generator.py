class SQLGenerationError(Exception):
    """Raised when a SQL query cannot be generated by the local model."""

    status_code = 502


class OllamaUnavailableError(SQLGenerationError):
    """Raised when the local Ollama server cannot be reached."""

    status_code = 503


class OllamaModelNotFoundError(SQLGenerationError):
    """Raised when the configured Ollama model is not installed."""

    status_code = 503


class OllamaTimeoutError(SQLGenerationError):
    """Raised when Ollama does not answer before the configured timeout."""

    status_code = 504


class InvalidGeneratedSQLError(SQLGenerationError):
    """Raised when Ollama output is empty or is not executable SQL."""

    status_code = 422


def clean_sql_output(response_text):
    """Remove Markdown wrappers while preserving the complete SQL statement."""
    if not isinstance(response_text, str):
        return ""

    clean_query = response_text.strip()
    clean_query = re.sub(
        r"^\s*```(?:sql|mysql)?\s*",
        "",
        clean_query,
        flags=re.IGNORECASE,
    )
    clean_query = re.sub(r"\s*```\s*$", "", clean_query)
    clean_query = clean_query.replace("```sql", "").replace("```SQL", "").replace("```", "")

    return clean_query.strip()


def extract_sql_statement(response_text):
    """Return a standalone SQL statement from a model response, if present.

    Some model/runtime combinations emit reasoning before the requested SQL.
    Looking for a statement at the beginning of a line avoids treating prose
    such as "select the name column" as SQL.
    """
    clean_query = clean_sql_output(response_text)
    is_valid, _ = validate_sql_query(clean_query)
    if is_valid:
        return clean_query

    statement_match = re.search(
        r"(?ims)^\s*(SELECT|WITH)\b.*?;",
        clean_query,
    )
    if statement_match:
        return statement_match.group(0).strip()

    return clean_query


def validate_sql_query(sql_query):
    """Validate that the result is one read-only SQL statement."""
    try:
        parsed = sqlparse.parse(sql_query)

        if not parsed or len(parsed) != 1 or not sql_query.strip():
            return False, "Invalid SQL syntax."

        statement_type = parsed[0].get_type()
        if statement_type != "SELECT":
            return (
                False,
                "Only one read-only SELECT statement is allowed.",
            )

        return True, None
    except Exception as exc:
        return False, str(exc)


def _schema_cache_key(schema):
    """Create a stable cache key that changes whenever the active schema changes."""
    return json.dumps(schema, sort_keys=True, separators=(",", ":"))


def generate_sql_query(natural_language_query):
    """Convert a natural-language request into an optimized MySQL query."""
    if not natural_language_query or not natural_language_query.strip():
        raise SQLGenerationError("The natural language query cannot be empty.")

    try:
        schema = get_schema()
    except Exception as exc:
        raise SQLGenerationError(f"Could not read the database schema: {exc}") from exc

    schema_key = _schema_cache_key(schema)
    dialect = get_sql_dialect().upper()
    relationships_key = json.dumps(get_confirmed_relationships(), sort_keys=True, separators=(",", ":"))
    return _generate_sql_query_cached(natural_language_query.strip(), schema_key, dialect, relationships_key)


@lru_cache(maxsize=128)
def _generate_sql_query_cached(natural_language_query, schema_key, dialect, relationships_key):
    """Generate SQL and reuse answers for identical questions and schemas."""
    schema = json.loads(schema_key)
    relationships = json.loads(relationships_key)
    schema_text = "\n".join(
        f"{table}: {', '.join(columns)}"
        for table, columns in schema.items()
    )

    dialect_rules = ""
    if dialect == "SQLITE":
        dialect_rules = (
            "- SQLite syntax: use LIMIT <number> after ORDER BY to limit rows.\n"
            "- Never use TOP, which is not valid SQLite syntax.\n"
        )

    relationship_text = "None confirmed. Do not invent relationships between tables."
    if relationships:
        relationship_text = "\n".join(
            "- {source_table}.{source_column} REFERENCES "
            "{target_table}.{target_column} ({relationship})".format(**relationship)
            for relationship in relationships
        )

    prompt = f"""You are an expert {dialect} SQL generator.

Database Schema:
{schema_text}

Confirmed Relationships:
{relationship_text}

Rules:
- Return a JSON object with exactly one key: "sql".
- The "sql" value must be one read-only SELECT statement.
- No explanation or markdown.
- Use only tables present in the schema.
- For multi-table queries, join tables only through the confirmed relationships above.
- Generate optimized SQL.
- Unless an aggregate returns a single value, use LIMIT {MAX_RESULT_ROWS} or fewer.
- Use JOIN instead of subqueries where appropriate.
- Use SUM, AVG, COUNT, GROUP BY, or other aggregation only when the user explicitly asks for an aggregate, total, average, count, or grouping.
- For "top", "highest", or "largest" requests without an explicit aggregate, return individual rows ordered by the requested column.

Dialect-specific rules:
{dialect_rules}

User Question:
{natural_language_query}
/no_think

SQL:"""

    payload = json.dumps(
        {
        "model": MODEL_NAME,
            "format": {
                "type": "object",
                "properties": {"sql": {"type": "string"}},
                "required": ["sql"],
                "additionalProperties": False,
            },
            "messages": [{"role": "user", "content": prompt}],
            "stream": False,
            "think": False,
            "keep_alive": OLLAMA_KEEP_ALIVE,
            "options": {
                "temperature": 0,
                "num_predict": OLLAMA_MAX_TOKENS,
            },
        }
    ).encode("utf-8")

    request = Request(
        f"{OLLAMA_BASE_URL}/api/chat",
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urlopen(request, timeout=OLLAMA_TIMEOUT_SECONDS) as response:
            body = json.loads(response.read().decode("utf-8"))
    except HTTPError as exc:
        if exc.code == 404:
            raise OllamaModelNotFoundError(
                f"Ollama model '{MODEL_NAME}' is not installed. "
                f"Run: ollama pull {MODEL_NAME}"
            ) from exc

        raise SQLGenerationError(f"Ollama returned HTTP {exc.code}.") from exc
    except URLError as exc:
        raise OllamaUnavailableError(
            f"Cannot reach Ollama at {OLLAMA_BASE_URL}. "
            "Start it with: ollama serve"
        ) from exc
    except TimeoutError as exc:
        raise OllamaTimeoutError(
            "Ollama request timed out while generating SQL."
        ) from exc
    except json.JSONDecodeError as exc:
        raise SQLGenerationError("Ollama returned an invalid response.") from exc

    message = body.get("message", {})
    raw_response = message.get("content", "")
    logger.info(
        "Ollama chat completed: model=%s done_reason=%s",
        body.get("model", MODEL_NAME),
        body.get("done_reason"),
    )

    try:
        structured_output = json.loads(raw_response)
        sql_value = structured_output.get("sql", "") if isinstance(structured_output, dict) else ""
        clean_query = clean_sql_output(sql_value)
    except json.JSONDecodeError:
        clean_query = extract_sql_statement(raw_response)

    if not clean_query:
        raise InvalidGeneratedSQLError("Ollama returned an empty SQL response.")

    is_valid, error_message = validate_sql_query(clean_query)
    if not is_valid:
        if body.get("done_reason") == "length":
            raise InvalidGeneratedSQLError(
                "Ollama reached its output-token limit before returning valid SQL. "
                "Increase OLLAMA_MAX_TOKENS or use a non-thinking SQL model."
            )
        raise InvalidGeneratedSQLError(
            f"Ollama generated invalid SQL: {error_message}"
        )

    return clean_query


def analyze_query(sql_query):
    """Return an optional execution plan and a conservative index suggestion."""
    try:
        with get_engine().connect() as connection:
            explain_query = f"EXPLAIN {sql_query}"
            result = connection.execute(text(explain_query))
            execution_plan = result.fetchall()

        return {
            "execution_plan": [dict(row._mapping) for row in execution_plan],
            "optimization_tips": "Consider indexes on columns frequently used in WHERE, JOIN, and ORDER BY clauses.",
        }
    except Exception as exc:
        return {"execution_plan": None, "optimization_tips": f"Could not generate execution plan: {exc}"}


def execute_query(sql_query, analyze=False):
    """Execute one validated SELECT query and return at most MAX_RESULT_ROWS rows."""
    is_valid, error_msg = validate_sql_query(sql_query)
    if not is_valid:
        print(f"SQL Validation Error: {error_msg}")
        return None

    try:
        with get_engine().connect() as connection:
            result = connection.execute(text(sql_query))
            fetched_results = result.fetchmany(MAX_RESULT_ROWS) if result.returns_rows else []

        results = [dict(row._mapping) for row in fetched_results]
        response = {"results": results, "row_limit": MAX_RESULT_ROWS}
        if analyze:
            response.update(analyze_query(sql_query))
        return response
    except SQLAlchemyError as exc:
        print(f"SQL Execution Error: {exc}")
        return None


